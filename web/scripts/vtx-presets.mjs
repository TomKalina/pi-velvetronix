// Generates src/ui/vtx-presets.ts from the Tone Room files in research/vtxprog/<author>/ (dev only).
// Programs that repeat an earlier one byte for byte, or have a value out of range, are left out.
//   node scripts/vtx-presets.mjs

import { build } from "esbuild";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const web = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));

// Per author folder: who made the files, where they come from, their licence.
const AUTHORS = {
  marcosmoura: {
    name: "Marcos Moura",
    repo: "https://github.com/marcosmoura/toneroom-presets",
    licence: "Beerware",
  },
};

// Bundle the protocol code (TypeScript) so the generator uses the same parser as the app.
const bundled = await build({
  stdin: { contents: `export { parseVtxprog, programToSettings } from "./src/protocol/vtxprog";`, resolveDir: web(""), loader: "ts" },
  bundle: true, format: "esm", platform: "node", write: false, logLevel: "warning",
});
const { parseVtxprog, programToSettings } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`);

// A program found in several files (e.g. the author's base clean sound) is listed once, without a band.
const filesOf = new Map();
for (const author of Object.keys(AUTHORS)) {
  for (const file of (await readdir(web(`research/vtxprog/${author}`))).filter((f) => f.endsWith(".vtxprog"))) {
    for (const e of parseVtxprog(new Uint8Array(await readFile(web(`research/vtxprog/${author}/${file}`))))) {
      if ("error" in e) continue;
      const key = Buffer.from(e.program.raw).toString("hex");
      filesOf.set(key, (filesOf.get(key) ?? new Set()).add(file));
    }
  }
}

const slug = (s) => s.normalize("NFD").replace(/[^\w\s-]/g, "").trim().toLowerCase().replace(/[\s_]+/g, "-");
const presets = [];
const seen = new Set();
const report = [];
for (const author of Object.keys(AUTHORS).sort()) {
  const meta = AUTHORS[author];
  const commit = (await readFile(web(`research/vtxprog/${author}/COMMIT`), "utf8")).trim();
  const files = (await readdir(web(`research/vtxprog/${author}`))).filter((f) => f.endsWith(".vtxprog")).sort();
  for (const file of files) {
    const bytes = new Uint8Array(await readFile(web(`research/vtxprog/${author}/${file}`)));
    const artist = file.replace(/\.vtxprog$/, "");
    let kept = 0, dup = 0, bad = 0;
    for (const e of parseVtxprog(bytes)) {
      if ("error" in e) { bad++; continue; }
      const key = Buffer.from(e.program.raw).toString("hex");
      if (seen.has(key)) { dup++; continue; }
      seen.add(key);
      kept++;
      const title = e.program.name.trim() || `Program ${e.index + 1}`;
      const shared = filesOf.get(key).size > 1;
      presets.push({
        id: `vtx-${author}-${slug(artist)}-${e.index + 1}`,
        title,
        artist: shared ? meta.name : artist,
        year: null,
        genre: "tone-room",
        description: `Preset z aplikace Tone Room od autora ${meta.name} (soubor „${file}“, program ${e.index + 1}). Licence ${meta.licence}. Autor neslibuje, že zní přesně jako kapela; záleží i na kytaře a snímačích.`,
        source: `${meta.repo}/blob/${commit}/presets/${encodeURIComponent(file)}`,
        sourceNote: "Soubor .vtxprog",
        ...programToSettings(e.program),
      });
    }
    report.push(`${file}: ${kept} kept, ${dup} duplicate, ${bad} invalid`);
  }
}

const header = `// Tone Room presets (.vtxprog) from research/vtxprog/, generated by scripts/vtx-presets.mjs. Do not edit.
// Marcos Moura's files: "THE BEERWARE LICENSE" (Revision 42): Marcos Moura wrote these files. As long as you
// retain this notice, you can do whatever you want with this stuff. If we meet someday, and you think this
// stuff is worth it, you can buy me a beer in return. (research/vtxprog/marcosmoura/LICENSE)

import type { SongPreset } from "./songs";

export const VTX_PRESETS: readonly SongPreset[] = `;
// Number arrays on one line.
const body = JSON.stringify(presets, null, 2).replace(/\[\s+([\d,\s]+?)\s+\]/g, (_, nums) => `[${nums.split(/,\s*/).join(", ")}]`);
await writeFile(web("src/ui/vtx-presets.ts"), `${header}${body};\n`);
console.log(report.join("\n"));
console.log(`vtx-presets: ${presets.length} presets`);
